"""Media data model.

::

    MediaAsset ──┬── MediaVariant     (renditions: mp3, mp4_720p, poster …)
                 ├── MediaAttachment  (who uses it: purpose + object id)
                 └── MediaAsset       (clips cut from it)
    DirectUpload                      (pending direct-to-storage uploads)

Files live in a private storage under random names; nothing is ever served
by its storage path.
"""

from __future__ import annotations

from django.conf import settings
from django.db import models
from django.utils.translation import gettext_lazy as _

from university.core.models import BaseModel
from university.core.uploads import uuid_upload_to

USER = settings.AUTH_USER_MODEL


def media_storage() -> object:
    from university.core.storage import get_storage
    from university.media.conf import media_settings

    return get_storage(media_settings.get("STORAGE", "private"))


class AssetStatus(models.TextChoices):
    PENDING = "pending", _("Pending")
    PROCESSING = "processing", _("Processing")
    READY = "ready", _("Ready")
    FAILED = "failed", _("Failed")


class AssetKind(models.TextChoices):
    AUDIO = "audio", _("Audio")
    VIDEO = "video", _("Video")
    IMAGE = "image", _("Image")
    DOCUMENT = "document", _("Document")


class MediaAsset(BaseModel):
    owner = models.ForeignKey(USER, null=True, on_delete=models.SET_NULL, related_name="media_assets")
    kind = models.CharField(max_length=16, choices=AssetKind.choices)
    status = models.CharField(max_length=16, choices=AssetStatus.choices, default=AssetStatus.PENDING)
    #: Empty only for a clip that hasn't been cut yet.
    file = models.FileField(
        upload_to=uuid_upload_to("media/originals"), storage=media_storage, max_length=255, blank=True
    )
    mime_type = models.CharField(max_length=100)
    size = models.PositiveBigIntegerField(default=0)
    sha256 = models.CharField(max_length=64, blank=True)
    #: Sanitised display name (never used as a path).
    original_name = models.CharField(max_length=120, blank=True)
    duration_seconds = models.FloatField(null=True, blank=True)
    width = models.PositiveIntegerField(null=True, blank=True)
    height = models.PositiveIntegerField(null=True, blank=True)
    error = models.CharField(max_length=64, blank=True)
    processed_at = models.DateTimeField(null=True, blank=True)
    #: For clips: the asset and range they were cut from.
    source = models.ForeignKey("self", null=True, blank=True, on_delete=models.SET_NULL, related_name="clips")
    clip_start = models.FloatField(null=True, blank=True)
    clip_end = models.FloatField(null=True, blank=True)

    class Meta:
        verbose_name = _("media asset")
        indexes = [
            models.Index(fields=["owner", "-created_at"], name="univ_media_owner"),
            models.Index(fields=["status", "created_at"], name="univ_media_status"),
        ]

    def __str__(self) -> str:
        return f"{self.kind} {self.pk}"


class MediaVariant(BaseModel):
    asset = models.ForeignKey(MediaAsset, on_delete=models.CASCADE, related_name="variants")
    name = models.CharField(max_length=32)
    file = models.FileField(upload_to=uuid_upload_to("media/variants"), storage=media_storage, max_length=255)
    mime_type = models.CharField(max_length=100)
    size = models.PositiveBigIntegerField(default=0)

    class Meta:
        verbose_name = _("media variant")
        constraints = [models.UniqueConstraint(fields=["asset", "name"], name="univ_media_variant_unique")]

    def __str__(self) -> str:
        return f"{self.name} of {self.asset_id}"


class MediaAttachment(models.Model):
    asset = models.ForeignKey(MediaAsset, on_delete=models.CASCADE, related_name="attachments")
    purpose = models.CharField(max_length=64)
    object_id = models.CharField(max_length=64)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = _("media attachment")
        constraints = [
            models.UniqueConstraint(fields=["asset", "purpose", "object_id"], name="univ_media_attachment_unique")
        ]
        indexes = [models.Index(fields=["purpose", "object_id"], name="univ_media_attachment_object")]

    def __str__(self) -> str:
        return f"{self.asset_id} → {self.purpose}:{self.object_id}"


class DirectUpload(BaseModel):
    class Status(models.TextChoices):
        PENDING = "pending", _("Pending")
        COMPLETED = "completed", _("Completed")
        FAILED = "failed", _("Failed")

    owner = models.ForeignKey(USER, on_delete=models.CASCADE, related_name="+")
    kind = models.CharField(max_length=16, choices=AssetKind.choices)
    #: Storage key the client uploads to (generated by us).
    key = models.CharField(max_length=255, unique=True)
    declared_mime_type = models.CharField(max_length=100)
    expected_size = models.PositiveBigIntegerField()
    original_name = models.CharField(max_length=120, blank=True)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.PENDING)
    expires_at = models.DateTimeField()
    asset = models.OneToOneField(MediaAsset, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")

    class Meta:
        verbose_name = _("direct upload")

    def __str__(self) -> str:
        return self.key
